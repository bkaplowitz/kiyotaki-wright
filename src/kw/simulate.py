"""Population learning harness: the Algorithm 3 shell, identical across learners.

Implements paper Algorithm 3 (p. 38) verbatim: for each of R rounds, a random
matching over current holdings is drawn, every matched pair exchanges meeting
observations and trade decisions before the (possibly executed) swap, and
*then* a population-wide consumption pass runs for every agent — the
consumption sweep is nested inside each round, not hoisted to run once per
iteration. This is the only reading consistent with the Bellman kernel
(B3)-(B4), which alternates a trade stage and a consumption stage within a
single period (architecture.md §7.3, §7.5); a once-per-iteration consumption
pass would leave (G-1) of every G rounds without any physical
consumption/production transition, which is not what (B3)-(B4) describe.
`evaluate_fixed` uses the identical match -> trade -> consume round structure
with Bernoulli-sampled fixed policies in place of a learner.

`simulate.py` owns everything that must be identical across learners
(architecture.md §7.5, the fairness contract): population init, the
matching-RNG, trade resolution, the (D1) stopping rule, deployment
extraction, and fixed-policy evaluation. A `Learner` (`learners/base.py`)
contributes only action selection, record ingestion, end-of-iteration
bookkeeping (returning Delta-bar_n), and its deployment policy; it never
touches matching, holdings bookkeeping, or the stopping rule.

`_run_trade_round` also calls an optional `observe_meeting_agent(agent, i,
k, j_good)` hook, for both agents of every meeting, before either agent's
`trade_action`, guarded by `hasattr` so learners that don't define it (e.g.
`MuZeroLearner`, whose meeting counts already come through
`observe_meeting`) are unaffected. The Stage-2 differential Q-learning
extension (Task 15) uses it to complete a consumption-stage TD update that
had to be deferred at `observe_cons` time until the next meeting reveals
the bootstrap good j'.

RNG discipline (§12.2): `run_learning` builds exactly one
`np.random.default_rng(seed)`, used both for the per-round matching
permutation and passed through as the `rng` argument to every
`learner.trade_action` / `learner.cons_action` call, so a run is fully
reproduced by (econ, learner state machine, cfg, seed). Matched pairs are
processed in draw order (perm[2m], perm[2m+1]) and both agents' trade records
are appended online in that same order.

Stopping rule (D1): paper Algorithm 4 line 7 breaks at the first 0-based
iteration n with n >= n_min + p - 1 whose last p deltas all satisfy
Delta-bar <= delta, which in this file's 1-based iteration count is the
first n >= n_min + patience carrying a live streak of at least patience.
The gate places the entire triggering window strictly after iteration
n_min, so a sub-threshold streak straddling n_min cannot stop the loop
early (the Algorithm 4 pseudocode is stricter than the section 6.3.4
prose "for p consecutive iterations, after n_min", and governs).
Deployment extraction (`learner.deployment_policy()`) always runs, whether
the loop stopped early or hit the n_iters_max cap.

mu_star (§12.7) seeds `distributions.invariant` from the *terminal* empirical
holdings distribution rather than the paper's idealized f(i)-everyone
initial condition: mu0[i] is the normalized histogram of holdings among
type-i agents at the end of learning, which selects the recurrent class
generated by the population's own learned trajectory.
"""

from dataclasses import dataclass

import numpy as np

from kw.distributions import invariant
from kw.economies import Economy
from kw.environment import next_holding_cons, reward_cons_table, trade_outcome
from kw.learners.base import ConsRecord, Learner, LearnerConfig, TradeRecord


@dataclass
class RunResult:
    alpha_star: np.ndarray
    beta_star: np.ndarray
    mu_star: np.ndarray
    trace: dict[str, list]
    n_iters: int
    holdings_final: np.ndarray


def _type_holdings_distribution(
    econ: Economy, types: np.ndarray, holdings: np.ndarray
) -> np.ndarray:
    """Row-normalized (I,G) per-type holdings distribution."""
    dist = np.zeros((econ.n_types, econ.n_goods), dtype=np.float64)
    for i in range(econ.n_types):
        counts = np.bincount(holdings[types == i], minlength=econ.n_goods)
        dist[i] = counts / counts.sum()
    return dist


def init_population(
    econ: Economy, cfg: LearnerConfig, rng: np.random.Generator
) -> tuple[np.ndarray, np.ndarray]:
    """N/|I| agents per type holding f[i]; economy C splits M0 onto fiat (§12.8).

    Requires `cfg.n_agents` divisible by `econ.n_types` (even population per
    type) and even overall (perfect pairwise matching); both violations raise
    loudly rather than silently dropping agents.
    """
    n_agents = cfg.n_agents
    if n_agents % econ.n_types != 0:
        raise ValueError(
            f"n_agents={n_agents} not divisible by n_types={econ.n_types}"
        )
    if n_agents % 2 != 0:
        raise ValueError(f"n_agents={n_agents} must be even for perfect pairwise matching")

    per_type = n_agents // econ.n_types
    types = np.repeat(np.arange(econ.n_types, dtype=np.int64), per_type)
    holdings = np.repeat(econ.f, per_type)

    if econ.fiat_idx is not None:
        n_fiat = round(econ.M0 * per_type)
        for i in range(econ.n_types):
            start = i * per_type
            fiat_positions = rng.choice(per_type, size=n_fiat, replace=False)
            holdings[start + fiat_positions] = econ.fiat_idx

    return types, holdings


def _run_trade_round(
    econ: Economy,
    learner: Learner,
    types: np.ndarray,
    holdings: np.ndarray,
    rng: np.random.Generator,
) -> int:
    """One round's matching + trade stage; returns the count of executed exchanges."""
    n_agents = types.shape[0]
    perm = rng.permutation(n_agents)
    exchanges = 0
    for m in range(n_agents // 2):
        a, b = int(perm[2 * m]), int(perm[2 * m + 1])
        i_a, i_b = int(types[a]), int(types[b])
        h_a, h_b = int(holdings[a]), int(holdings[b])

        learner.observe_meeting(i_a, h_b)
        learner.observe_meeting(i_b, h_a)

        if hasattr(learner, "observe_meeting_agent"):
            learner.observe_meeting_agent(agent=a, i=i_a, k=h_a, j_good=h_b)
            learner.observe_meeting_agent(agent=b, i=i_b, k=h_b, j_good=h_a)

        lam_a = learner.trade_action(i_a, h_a, h_b, rng)
        lam_b = learner.trade_action(i_b, h_b, h_a, rng)
        new_h_a, new_h_b = trade_outcome(h_a, h_b, lam_a, lam_b)
        if new_h_a != h_a:
            exchanges += 1

        holdings[a], holdings[b] = new_h_a, new_h_b

        rec_a = TradeRecord(agent=a, i=i_a, k=h_a, j=h_b, lam=lam_a, h_next=new_h_a, r=0.0)
        rec_b = TradeRecord(agent=b, i=i_b, k=h_b, j=h_a, lam=lam_b, h_next=new_h_b, r=0.0)
        learner.observe_trade(rec_a)
        learner.observe_trade(rec_b)
    return exchanges


def _run_cons_round(
    econ: Economy,
    learner: Learner,
    types: np.ndarray,
    holdings: np.ndarray,
    rng: np.random.Generator,
    r_table: np.ndarray,
    next_h_table: np.ndarray,
) -> None:
    """One round's population-wide consumption stage, in agent-index order."""
    n_agents = types.shape[0]
    for a in range(n_agents):
        i_a, h_a = int(types[a]), int(holdings[a])
        gamma = learner.cons_action(i_a, h_a, rng)
        if gamma == 1 and not econ.gamma_feasible[i_a, h_a]:
            raise ValueError(
                f"cons_action returned gamma=1 at gamma-infeasible (i={i_a}, h={h_a})"
            )
        r = float(r_table[i_a, h_a, gamma])
        h_next = int(next_h_table[i_a, h_a, gamma])
        holdings[a] = h_next
        learner.observe_cons(ConsRecord(agent=a, i=i_a, h=h_a, gamma=gamma, h_next=h_next, r=r))


def run_learning(econ: Economy, learner: Learner, cfg: LearnerConfig, seed: int) -> RunResult:
    """Algorithms 3-4 shell: R-round iterations to the (D1) stopping rule, then deployment."""
    rng = np.random.default_rng(seed)
    types, holdings = init_population(econ, cfg, rng)
    r_table = reward_cons_table(econ)
    next_h_table = next_holding_cons(econ)

    trace: dict[str, list] = {"agg_holdings": [], "trade_volume": [], "delta": []}
    streak = 0
    n_iters = 0
    for n in range(1, cfg.n_iters_max + 1):
        n_iters = n
        exchanges = 0
        for _ in range(cfg.rounds):
            exchanges += _run_trade_round(econ, learner, types, holdings, rng)
            _run_cons_round(econ, learner, types, holdings, rng, r_table, next_h_table)

        delta = float(learner.end_iteration(n))
        trace["agg_holdings"].append(_type_holdings_distribution(econ, types, holdings))
        trace["trade_volume"].append(int(exchanges))
        trace["delta"].append(delta)

        streak = streak + 1 if delta <= cfg.delta_stop else 0
        if n >= cfg.n_min + cfg.patience and streak >= cfg.patience:
            break

    alpha_star, beta_star = learner.deployment_policy()
    mu0 = _type_holdings_distribution(econ, types, holdings)
    mu_star = invariant(econ, mu0, alpha_star, beta_star)

    return RunResult(
        alpha_star=alpha_star,
        beta_star=beta_star,
        mu_star=mu_star,
        trace=trace,
        n_iters=n_iters,
        holdings_final=holdings.copy(),
    )


def evaluate_fixed(
    econ: Economy,
    alpha: np.ndarray,
    beta: np.ndarray,
    cfg: LearnerConfig,
    rng: np.random.Generator,
) -> dict:
    """Fixed-policy simulation (paper's evaluation protocol): no learner, no records.

    `cfg.eval_rounds` rounds of match -> Bernoulli(alpha) trade -> Bernoulli(beta)
    consumption (masked by gamma-feasibility); the (I,G) per-type holdings
    distribution is recorded every `cfg.eval_interval` rounds.
    """
    types, holdings = init_population(econ, cfg, rng)
    n_agents = types.shape[0]
    next_h_table = next_holding_cons(econ)

    holdings_series: list[np.ndarray] = []
    trade_volume: list[int] = []

    for r in range(1, cfg.eval_rounds + 1):
        perm = rng.permutation(n_agents)
        exchanges = 0
        for m in range(n_agents // 2):
            a, b = int(perm[2 * m]), int(perm[2 * m + 1])
            i_a, i_b = int(types[a]), int(types[b])
            h_a, h_b = int(holdings[a]), int(holdings[b])

            offer_a = int(rng.random() < alpha[i_a, h_a, h_b])
            offer_b = int(rng.random() < alpha[i_b, h_b, h_a])
            new_h_a, new_h_b = trade_outcome(h_a, h_b, offer_a, offer_b)
            if new_h_a != h_a:
                exchanges += 1
            holdings[a], holdings[b] = new_h_a, new_h_b

        for a in range(n_agents):
            i_a, h_a = int(types[a]), int(holdings[a])
            if econ.gamma_feasible[i_a, h_a]:
                gamma = int(rng.random() < beta[i_a, h_a])
            else:
                gamma = 0
            holdings[a] = int(next_h_table[i_a, h_a, gamma])

        trade_volume.append(int(exchanges))
        if r % cfg.eval_interval == 0:
            holdings_series.append(_type_holdings_distribution(econ, types, holdings))

    return {
        "holdings_series": holdings_series,
        "holdings_final": holdings.copy(),
        "trade_volume": trade_volume,
    }
